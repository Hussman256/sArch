describe("account decoders", () => {
  it("globalConfig", () => {
    const { data, fields } = fixtures.accounts.globalConfig;
    expect(hexToBytes(data)).toHaveLength(GLOBAL_CONFIG_LEN);
    expect(plain(decodeGlobalConfig(hexToBytes(data)))).toEqual(fields);
  });

  for (const expected of fixtures.accounts.proposals as { name: string; data: string; fields: object }[]) {
    it(`proposal: ${expected.name}`, () => {
      expect(plain(decodeProposal(hexToBytes(expected.data)))).toEqual(expected.fields);
    });
  }

  it("works out where a proposal stands", () => {
    const current = decodeGlobalConfig(hexToBytes(fixtures.accounts.globalConfig.data));
    const [setConfig, pause] = (fixtures.accounts.proposals as { data: string }[]).map((entry) =>
      decodeProposal(hexToBytes(entry.data)),
    ) as [Proposal, Proposal];
    const admins = current.active.admins;

    // Approved by the first and third of three admins, two needed.
    expect(approvers(setConfig, admins)).toEqual([admins.members[0], admins.members[2]]);
    const approvedAt = setConfig.approvedAt;
    const delay = BigInt(current.active.timelockSecs);

    // A config change waits out the timelock from the approval that reached the threshold...
    expect(proposalState(setConfig, current, approvedAt + delay - 1n)).toEqual({
      status: "waiting",
      readyAt: approvedAt + delay,
    });
    expect(proposalState(setConfig, current, approvedAt + delay)).toEqual({ status: "ready" });
    // ...a pause does not wait at all.
    expect(proposalState(pause, current, approvedAt)).toEqual({ status: "ready" });

    expect(proposalState({ ...setConfig, approvals: 0b001, approvedAt: 0n }, current, approvedAt + delay)).toEqual({
      status: "needs-approvals",
      have: 1,
      need: 2,
    });
    expect(proposalState({ ...setConfig, executedAt: 5n }, current, 0n)).toEqual({ status: "executed", at: 5n });
    // Made under an earlier config: dead, however many approvals it has.
    expect(proposalState({ ...setConfig, epoch: current.epoch - 1 }, current, approvedAt + delay)).toEqual({
      status: "stale",
    });
  });

  it("curve", () => {
    const { data, fields } = fixtures.accounts.curve;
    expect(plain(decodeCurve(hexToBytes(data)))).toEqual(fields);
  });

  it("position", () => {
    const { data, fields } = fixtures.accounts.position;
    expect(plain(decodePosition(hexToBytes(data)))).toEqual(fields);
  });

  it("pool", () => {
    const { data, fields } = fixtures.accounts.pool;
    expect(plain(decodePool(hexToBytes(data)))).toEqual(fields);
  });

  it("refuse an account of another kind", () => {
    const curve = hexToBytes(fixtures.accounts.curve.data);
    expect(() => decodePool(curve)).toThrow(/not a pool account/);
    expect(() => decodeGlobalConfig(curve)).toThrow(/not a config account/);
    expect(() => decodeCurve(hexToBytes(fixtures.accounts.pool.data))).toThrow(/not a curve account/);
  });

  it("refuse truncated data", () => {
    const curve = hexToBytes(fixtures.accounts.curve.data);
    expect(() => decodeCurve(curve.subarray(0, curve.length - 1))).toThrow(RangeError);
  });
});

describe("error codes", () => {
  it("match the Rust error enum, code for code and word for word", () => {
    expect(PROGRAM_ERRORS).toEqual(fixtures.errors);
  });

  it("are recognised in the forms a node reports them", () => {
    expect(programError(305)?.name).toBe("SlippageExceeded");
    expect(programError(999)).toBeUndefined();
    expect(findProgramError("Custom program error: 0x131")?.name).toBe("SlippageExceeded");
    expect(findProgramError("custom program error: 0x130")?.name).toBe("WalletCapExceeded");
    expect(findProgramError("ProgramError(Custom(303))")?.name).toBe("CreatorBuyTooSmall");
    expect(findProgramError(undefined, ["Program log: hi", "failed: custom program error: 0x7b"])?.name).toBe(
      "CurveComplete",
    );
    expect(findProgramError("insufficient funds")).toBeUndefined();
    // A custom code from some other program is not mistaken for one of ours.
    expect(findProgramError("custom program error: 0x1")).toBeUndefined();
  });
});

describe("events", () => {
  interface EventFixture {
    name: string;
    data: string;
    program: string;
    authority: string;
    instructionData: string;
    fields: object;
  }
  const events = fixtures.events as EventFixture[];

  for (const expected of events) {
    it(`${expected.name} decodes`, () => {
      const event = decodeEvent(hexToBytes(expected.data));
      expect(event?.type).toBe(expected.name);
      const { type: _type, ...fields } = plain(event) as Record<string, unknown>;
      expect(fields).toEqual(expected.fields);
      // The same event as the instruction that records it on chain.
      expect(decodeEventInstruction(hexToBytes(expected.instructionData))).toEqual(event);
      // And encoding it gives back the program's bytes exactly.
      expect(bytesToHex(encodeEvent(event!))).toBe(expected.data);
      expect(bytesToHex(encodeEventInstruction(event!))).toBe(expected.instructionData);
    });
  }

  it("uses the same instruction tag as the programs", () => {
    expect(EVENT_IX_TAG).toBe(fixtures.eventInstructionTag);
    // Ordinary instruction data, or an event without the tag, is not an event.
    expect(decodeEventInstruction(hexToBytes(events[1]!.data))).toBeNull();
    expect(decodeEventInstruction(Uint8Array.of(1, 2, 3))).toBeNull();
    expect(decodeEventInstruction(new Uint8Array())).toBeNull();
  });

  it("reads events from the calls a transaction recorded, and only genuine ones", () => {
    const byName = (name: string) => events.find((event) => event.name === name)!;
    const impostor = bytesToAddress(new Uint8Array(32).fill(0xee));
    const keys = [
      bytesToAddress(new Uint8Array(32).fill(0x22)),
      DEFAULT_PROGRAM_IDS.launch,
      DEFAULT_PROGRAM_IDS.pool,
      DEFAULT_PROGRAM_IDS.fees,
      impostor,
    ];
    const call = (programIdIndex: number, dataHex: string) => ({
      stackHeight: 2,
      instruction: { programIdIndex, accounts: [0], data: hexToBytes(dataHex) },
    });
    const processed: ProcessedTransaction = {
      status: { type: "processed" },
      bitcoinTxid: null,
      logs: [],
      transaction: {
        version: 0,
        signatures: [],
        message: {
          header: { numRequiredSignatures: 1, numReadonlySignedAccounts: 0, numReadonlyUnsignedAccounts: 4 },
          accountKeys: keys,
          recentBlockhash: new Uint8Array(32),
          instructions: [],
        },
      },
      innerInstructions: [
        [
          call(1, byName("Trade").instructionData),
          // The same bytes sent to some other program are not our event...
          call(4, byName("Trade").instructionData),
          // ...and neither is a trade "recorded" by the pool program.
          call(2, byName("Trade").instructionData),
          // An ordinary inner call, such as a token transfer.
          call(1, "030a00000000000000"),
        ],
        [],
        [call(2, byName("PoolSwap").instructionData), call(3, byName("CreatorFeesClaimed").instructionData)],
      ],
    };
    expect(eventsOf(processed).map((event) => event.type)).toEqual(["Trade", "PoolSwap", "CreatorFeesClaimed"]);

    // A transaction the chain rejected has no events, whatever it got through first.
    expect(eventsOf({ ...processed, status: { type: "failed", message: "custom program error: 0x131" } })).toEqual([]);
    expect(eventsOf({ ...processed, status: { type: "queued" } })).toEqual([]);
  });

  it("rejects bytes that are not exactly one event", () => {
    const trade = hexToBytes(fixtures.events[1].data);
    expect(decodeEvent(trade.subarray(0, trade.length - 1))).toBeNull();
    expect(decodeEvent(Uint8Array.from([...trade, 0]))).toBeNull();
    expect(decodeEvent(Uint8Array.of(200))).toBeNull();
    expect(decodeEvent(new Uint8Array())).toBeNull();
  });
});

describe("transactions", () => {
  const expected = fixtures.transaction;
  const byName = new Map((fixtures.instructions as WireInstruction[]).map((entry) => [entry.name, entry]));
  const instructions: Instruction[] = (expected.instructionNames as string[]).map((name) => {
    const entry = byName.get(name)!;
    return { programId: entry.programId, accounts: entry.accounts, data: hexToBytes(entry.data) };
  });
  const message = compileMessage(instructions, expected.payer, hexToBytes(expected.recentBlockhash));
  const transaction = {
    version: 0 as const,
    signatures: [hexToBytes(expected.signature)],
    message,
  };

  it("compile to the same account order and header as the node's SDK", () => {
    expect(message.accountKeys).toEqual(expected.accountKeys);
    expect(message.header).toEqual(expected.header);
  });

  it("serialize the message identically", () => {
    expect(bytesToHex(serializeMessage(message))).toBe(expected.message);
  });

  it("produce the same signing payload", () => {
    expect(signingPayload(message)).toBe(expected.signingPayload);
    expect(signingPayload(message)).toMatch(/^[0-9a-f]{64}$/);
  });

  it("serialize the transaction identically and derive the same ID", () => {
    expect(bytesToHex(serializeTransaction(transaction))).toBe(expected.serialized);
    expect(transactionId(transaction)).toBe(expected.txid);
  });

  it("survive a round trip through the node's JSON form", () => {
    const json = JSON.parse(JSON.stringify(transactionToJson(transaction)));
    expect(json.message.account_keys[0]).toHaveLength(32);
    expect(json.signatures[0]).toHaveLength(64);
    const back = transactionFromJson(json);
    expect(bytesToHex(serializeTransaction(back))).toBe(expected.serialized);
  });

  it("fit Arch's transaction size limit with room to spare", () => {
    expect(serializeTransaction(transaction).length).toBeLessThanOrEqual(1232);
  });
});
