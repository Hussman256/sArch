#!/usr/bin/env node
// Creates the secp256k1 keys that give each on-chain program its ID, and writes
// those IDs where the Rust programs and the TypeScript SDK read them.
//
//   node scripts/program-keys.mjs dev              deterministic, PUBLIC keys for a local chain
//   node scripts/program-keys.mjs generate <name>  fresh random keys for a real deployment
//   node scripts/program-keys.mjs use <name>       point the build at an existing key set
//
// A program's ID is the x-only public key of its key. Whoever holds the key can
// deploy to that ID, so the `dev` set (derived from the fixed strings below and
// therefore known to everyone) must never be deployed to a public network.
// `scripts/deploy.mjs` refuses to do so.
//
// Each set also has an `authority` key. It pays for deployment and is the only
// key the config program lets initialise it, which closes the window in which
// a stranger could initialise a freshly deployed program first.
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { schnorr } from "@noble/curves/secp256k1.js";
import { sha256 } from "@noble/hashes/sha2.js";
import { base58, hex } from "@scure/base";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PROGRAMS = ["config", "launch", "fees", "pool"];
const DESCRIPTIONS = {
  config: "Config program: fees, curve shape and quote assets, under the admin authority.",
  launch: "Launch program: creates coins and runs their bonding curves.",
  fees: "Fee vault program: holds trade fees until the platform and creators claim them.",
  pool: "Pool program: the locked-liquidity pool a curve graduates into.",
};

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

function keyDir(name) {
  if (!/^[a-z0-9][a-z0-9-]*$/.test(name)) fail(`key set name must be lowercase letters, digits and dashes, got "${name}"`);
  return join(ROOT, "keys", name);
}

function writeKey(path, secret) {
  // Owner-only where the platform honours it. `wx` refuses to replace a key.
  writeFileSync(path, `${hex.encode(secret)}\n`, { mode: 0o600, flag: "wx" });
}

function readKey(path) {
  const secret = hex.decode(readFileSync(path, "utf8").trim());
  if (secret.length !== 32) fail(`${path} is not a 32-byte hex secret key`);
  return secret;
}

function programId(secret) {
  return base58.encode(schnorr.getPublicKey(secret));
}

function writeIds(keySet, ids, authority) {
  const isDev = keySet === "dev";
  const json = { keySet, ...ids, initialAuthority: authority };
  writeFileSync(join(ROOT, "deploy", "program-ids.json"), `${JSON.stringify(json, null, 2)}\n`);

  const modules = PROGRAMS.map(
    (name) => `/// ${DESCRIPTIONS[name]}\npub mod ${name} {\n    arch_program::declare_id!("${ids[name]}");\n}\n`,
  ).join("\n");
  const rust = `//! Program IDs for the \`${keySet}\` key set.
//!
//! Generated by \`scripts/program-keys.mjs\`. Do not edit by hand: the same IDs
//! are written to \`deploy/program-ids.json\` for the TypeScript SDK, and the two
//! must agree.
${
  isDev
    ? `//!
//! These are the public development keys. Anyone can derive their secrets, so
//! they are for a local chain only.
`
    : ""
}
use arch_program::pubkey::Pubkey;

/// True when the IDs below come from the public development keys.
pub const IS_DEV_KEY_SET: bool = ${isDev};

/// The only key allowed to initialise the config program after deployment.
pub const INITIAL_AUTHORITY: Pubkey =
    Pubkey::from_str_const("${authority}");

${modules}`;
  writeFileSync(join(ROOT, "crates", "archpad-interface", "src", "ids.rs"), rust);

  const typescript = `// Program IDs for the \`${keySet}\` key set.
//
// Generated by \`scripts/program-keys.mjs\`. Do not edit by hand.

export const PROGRAM_IDS = {
  /** Which key set these IDs come from. \`dev\` is public and for a local chain only. */
  keySet: ${JSON.stringify(keySet)},
${PROGRAMS.map((name) => `  ${name}: ${JSON.stringify(ids[name])},`).join("\n")}
  /** The only key allowed to initialise the config program. */
  initialAuthority: ${JSON.stringify(authority)},
} as const;
`;
  writeFileSync(join(ROOT, "packages", "sdk", "src", "generated", "program-ids.ts"), typescript);
}

function report(keySet, ids, authority) {
  console.log(`key set: ${keySet}`);
  for (const name of PROGRAMS) console.log(`  ${name.padEnd(9)} ${ids[name]}`);
  console.log(`  authority ${authority}`);
  console.log("wrote deploy/program-ids.json, crates/archpad-interface/src/ids.rs and packages/sdk/src/generated/program-ids.ts");
}

const [mode, name] = process.argv.slice(2);

if (mode === "dev") {
  const dir = keyDir("dev");
  mkdirSync(dir, { recursive: true });
  const ids = {};
  for (const program of [...PROGRAMS, "authority"]) {
    const secret = sha256(new TextEncoder().encode(`archpad public dev key: ${program}`));
    const path = join(dir, `${program}.key`);
    if (!existsSync(path)) writeKey(path, secret);
    ids[program] = programId(secret);
  }
  const { authority, ...programIds } = ids;
  writeIds("dev", programIds, authority);
  report("dev", programIds, authority);
} else if (mode === "generate") {
  if (!name) fail("usage: program-keys.mjs generate <name>");
  if (name === "dev") fail('"dev" is reserved for the public development keys');
  const dir = keyDir(name);
  if (existsSync(dir)) fail(`keys/${name} already exists; refusing to overwrite keys`);
  mkdirSync(dir, { recursive: true });
  const ids = {};
  for (const program of [...PROGRAMS, "authority"]) {
    const secret = randomBytes(32);
    writeKey(join(dir, `${program}.key`), secret);
    ids[program] = programId(secret);
  }
  const { authority, ...programIds } = ids;
  writeIds(name, programIds, authority);
  report(name, programIds, authority);
  console.log(`\nkeys/${name}/ holds the secret keys. It is gitignored: back it up somewhere safe.`);
} else if (mode === "use") {
  if (!name) fail("usage: program-keys.mjs use <name>");
  const dir = keyDir(name);
  const ids = {};
  for (const program of [...PROGRAMS, "authority"]) {
    const path = join(dir, `${program}.key`);
    if (!existsSync(path)) fail(`missing ${path}`);
    ids[program] = programId(readKey(path));
  }
  const { authority, ...programIds } = ids;
  writeIds(name, programIds, authority);
  report(name, programIds, authority);
} else {
  fail("usage: program-keys.mjs dev | generate <name> | use <name>");
}
